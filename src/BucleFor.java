public class BucleFor {
    public static void main(String[] args) {
        /*Ejercicio: Escribe un programa que sume los números del 1 al 10
        usando un bucle for.*/

       int suma = 0;

       for (int i = 1; i < 11; i= i+1){
           suma = suma + i;

           System.out.println("La suma del número " + i + " es " + suma);
       }



    }
}


